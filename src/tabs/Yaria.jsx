function highlight(text, words) {
  if (!words.length) return <span>{text}</span>
  let result = text
  words.forEach(w => {
    result = result.split(w).join(`|||${w}|||`)
  })
  return result.split('|||').map((part, i) =>
    words.includes(part)
      ? <mark key={i} className="hi-word">{part}</mark>
      : <span key={i}>{part}</span>
  )
}

export default function Yaria() {
  return (
    <div className="para-list">
      {PARAS.map((p, i) => (
        <div key={i} className={`para-item${p.hi.length ? ' para-highlight' : ''}`}>
          <div className="para-num">{i + 1}-р өгүүлбэр</div>
          <div className="para-text">{highlight(p.text, p.hi)}</div>
        </div>
      ))}
    </div>
  )
}
